import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const packageRoot = join(dirname(fileURLToPath(import.meta.url)), '..');

/*
 * Order matters only for readability — CSS variables resolve at use time.
 * Concatenating (rather than shipping a chain of `@import`s) means consumers
 * get one self-contained file and Tailwind never has to resolve package
 * specifiers inside our own CSS.
 */
const layers = ['base.css', 'palette.css', 'semantic.css', 'bridge.css'];

const banner = `/* sawitSvelte design tokens — generated by packages/tokens/scripts/build-css.mjs.
 * Do not edit dist/theme.css directly; edit the files in src/. */

`;

const contents = await Promise.all(
	layers.map((file) => readFile(join(packageRoot, 'src', file), 'utf8'))
);

await mkdir(join(packageRoot, 'dist'), { recursive: true });
await writeFile(join(packageRoot, 'dist', 'theme.css'), banner + contents.join('\n'), 'utf8');

console.log(`tokens: built dist/theme.css from ${layers.length} layers`);
